def _style_block(style_sample):
    """저자 문체 샘플을 프롬프트에 넣을 블록으로 만든다 (없으면 빈 문자열)."""
    sample = (style_sample or "").strip()[:STYLE_SAMPLE_MAX]
    if not sample:
        return ""
    return f"""
[저자 문체 샘플 — 저자가 직접 쓴 글]
{sample}

위 샘플의 말투(존댓말/반말, 어미), 문장 길이와 리듬, 자주 쓰는 표현과 말버릇,
문단 호흡을 따라 써. 샘플의 내용·사실은 가져오지 마 (사실은 아래 재료만 써).
샘플이 짧은 SNS 글이어도 문체 특징만 참고하고 블로그 글 구조는 유지해.
시스템 지침의 말투 예시와 샘플의 말투가 다르면 샘플을 우선해.
"""


def draft_post(topic, key_points, personal_take="", platform="네이버 블로그",
               target_keyword="", sources=None, past_titles=None, style_sample=None):
    """
    블로그 글 초안을 생성한다.

    topic: 글 주제 (한 줄)
    key_points: 실제 사실/숫자/경험 리스트 (list[str]) — 본인이 직접 채워야 함.
                AI가 지어내지 않도록 여기 없는 내용은 쓰지 않는다.
    personal_take: 저자의 의견/판단 (선택, 없으면 사실 전달 위주로 작성)
    platform: "네이버 블로그" / "티스토리" / "워드프레스" — 톤·소제목 밀도·
              사진 제안 개수가 이에 맞춰 달라진다.
    target_keyword: 이 글로 잡고 싶은 검색어 (선택, 없으면 AI가 주제에서 고름)
    sources: 인용할 근거 자료 리스트 (list[str], 선택) — 식약처 고시, EFSA 의견서,
             통계 등. 건강·돈 주제는 구글이 근거(E-E-A-T)를 엄격히 보기 때문.
    past_titles: 같은 플랫폼에 전에 쓴 글 제목들 (list[str], 선택) — 내부 링크
                 추천용. 관련 있는 것만 [내부링크 제안]으로 넣는다.
    style_sample: 저자 문체 샘플 (선택, None이면 my_style.txt에서 읽음)
    """
    if not key_points:
        raise ValueError("key_points가 비어 있습니다. 구체적 사실/숫자/경험을 최소 1개 이상 넣어주세요.")

    points_text = "\n".join(f"- {p}" for p in key_points)
    opening_style = random.choice(OPENING_STYLES)
    style_hint = PLATFORM_STYLE_HINTS.get(platform, PLATFORM_STYLE_HINTS["네이버 블로그"])
    today = f"{datetime.now().year}년 {datetime.now().month}월"
    keyword_text = target_keyword or "(지정 안 함 — 주제에서 사람들이 실제로 검색할 법한 검색어 하나를 골라서 그걸 기준으로 써)"

    if sources:
        sources_text = "\n".join(f"- {s}" for s in sources)
        sources_block = f"""
참고 자료/출처 (근거로 인용할 것 — 목록에 없는 기관·문서·수치를 출처로 지어내지 마):
{sources_text}
"""
    else:
        sources_block = "\n참고 자료/출처: (별도 입력 없음)\n"

    if past_titles:
        titles_text = "\n".join(f"- {t}" for t in past_titles)
        links_rule = f"""   - 내부 링크: 아래는 이 블로그에 전에 쓴 글 제목들이야. 이 중 이 글과
     실제로 관련 있는 글이 있으면, 본문에서 그 글을 언급하기 자연스러운 자리에
     독립된 줄로 [내부링크 제안] 글 제목 을 최대 2개까지 넣어줘. 관련 없으면
     넣지 말고, 이 글과 사실상 같은 주제(같은 글의 이전 버전)는 제외하고,
     목록에 없는 제목은 절대 지어내지 마.
{titles_text}
"""
    else:
        links_rule = ""

    if style_sample is None:
        style_sample = load_style_sample()

    prompt = f"""아래 정보로 블로그 글 초안을 써줘.
{_style_block(style_sample)}
주제: {topic}

타깃 키워드: {keyword_text}

제공된 사실/숫자/경험 (이것만 사용하고, 새로 지어내지 마 — 항목별 목록일 수도,
길게 이어 쓴 문단일 수도 있어. 문단이면 그 안에 든 사실·수치·경험·저자의 판단을
빠짐없이 읽어내서 글에 반영해):
{points_text}
{sources_block}
저자의 의견/입장: {personal_take or "(별도 입력 없음 — 사실 전달 위주로 작성)"}

플랫폼: {style_hint}

분량: 1500~2000자 내외 (제목·카테고리·메타설명·주소·태그는 별도)
형식: 마크다운 기호(#, * 등)는 쓰지 마. 아래 순서를 반드시 지켜줘:

1. 맨 첫 줄에 [제목] 타깃 키워드를 자연스럽게 한 번 포함한 제목.
   20~30자 내외, 낚시성 과장 문구 금지, 키워드를 억지로 반복하지 마.
2. 그다음 줄에 [카테고리] 이 글에 어울리는 블로그 카테고리명 1개
   (예: 건강기능식품, 재테크/투자 등 — 너무 잘게 쪼개지 않은 상식적인 수준.
   단, 글 내용과 모순되는 분류는 피해 — 예를 들어 "기능성 원료로 인정되지
   않았다"는 글을 "건강기능식품" 카테고리에 넣지 마).
3. 그다음 줄에 [메타설명] 검색결과 스니펫에 쓸 요약 1~2문장, 120~155자
   내외. 타깃 키워드를 자연스럽게 포함하고, 제목이랑 내용이 겹치지 않게,
   클릭하고 싶어지게 핵심만.
4. 그다음 줄에 [주소] 글 주소(URL)용 영문 슬러그. 소문자 영어 단어 3~6개를
   하이픈으로 연결 (예: probiotics-label-check). 타깃 키워드의 뜻을 담아줘.
5. 본문 — 첫 문단(첫 2~3문장 안)에 타깃 키워드가 자연스럽게 드러나야 해
   (검색엔진이 이 글이 뭘 다루는지 바로 알 수 있게. 단, 키워드를
   부자연스럽게 욱여넣지는 마). 소제목 중 최소 1개에는 타깃 키워드나
   그 자연스러운 변형을 넣어줘.
   도입부 스타일: {opening_style}
   "요즘"이나 "최근"으로 시작하는 문장, "~가 많이 보인다/늘고 있다"
   식으로 시장 트렌드부터 나열하며 시작하는 방식은 이미 여러 번 써서
   패턴이 됐으니 처음 두 문장 안에서는 절대 쓰지 마 (오프닝의 첫
   문장뿐 아니라 두 번째 문장에도 슬쩍 끼워넣지 마).
   - 소제목이 들어가는 줄은 맨 앞에 [소제목]을 붙여줘
     (예: [소제목] 균주명 없는 표시, 뭐가 문제인가). 개수는 위 "플랫폼"
     지침에 나온 개수를 따르고, 자연스러운 자리에만.
   - 체크리스트/조언 섹션 주의: "무엇을 확인해야 하는가", "고를 때
     체크할 것" 같은 정보형 소제목을 쓰더라도, "~인지 확인하세요",
     "~을 살펴보는 게 좋다" 같은 뻔한 조언체로만 채우지 마. 위에 준
     사실/경험 중 실제로 구체적인 것(수치, 실무에서 본 사례, 저자의
     판단 근거)을 그 섹션 안에도 반드시 끌어와서 채워.
   - 사진/그래프/지도를 넣으면 좋을 자리에는 그 지점에 독립된 줄로
     아래처럼 제안해줘:
     [사진 제안] 어떤 사진이 좋을지 짧은 설명 / ALT: "자연스러운 대체 텍스트" / 파일명: english-file-name.jpg
     [그래프 제안] 어떤 데이터를 시각화하면 좋을지 / ALT: "자연스러운 대체 텍스트" / 파일명: english-file-name.png
     [지도 제안] 어떤 장소/위치가 좋을지 / ALT: "자연스러운 대체 텍스트" / 파일명: english-file-name.png
     실제로 어울리는 자리에만 넣고, 없으면 억지로 만들지 마. [그래프 제안]은
     위에 제공된 숫자가 있을 때만 하고, 없는 데이터를 지어내지 마.
     ALT 텍스트는 이미지에 실제로 뭐가 보이는지 설명하는 식으로 쓰고,
     키워드 나열하지 마. 파일명은 이미지 내용을 담은 소문자 영어 단어를
     하이픈으로 연결해 (구글 이미지 검색이 파일명도 읽음).
   - 근거 인용: 위 "참고 자료/출처"가 있으면, 관련 주장을 할 때 본문에서
     "식약처 ○○ 고시에 따르면"처럼 자연스럽게 출처를 밝혀줘 (각주나 링크
     목록 형식 말고 문장 안에서). 규제·효능·수치처럼 근거가 꼭 필요한
     주장인데 제공된 출처가 없으면, 출처를 지어내지 말고 그 문장 바로 뒤에
     [출처 필요: 어떤 근거가 필요한지] 라고 표시해줘.
{AI_HABITS_RULE}
   - 기준일: 규제·기준·가격·통계처럼 시간이 지나면 바뀔 수 있는 정보를
     다룬다면, 그 정보가 처음 나오는 문단에 "{today} 기준"이라고 자연스럽게
     한 번 밝혀줘. 그런 정보가 없으면 넣지 마.
{links_rule}6. 맨 마지막 줄에 [태그] 검색 키워드 5~7개를 쉼표로 구분해서 (# 기호 없이).
   - 첫 번째 태그는 위 "타깃 키워드"를 그대로 써.
   - 나머지는 사람들이 실제로 검색창에 칠 법한 검색어로 골라: 타깃 키워드에
     검색 의도를 붙인 변형(예: "~ 함량", "~ 섭취량", "~ 가격 비교", "~ 고르는 법")과,
     이 글 본문에서 실제로 다룬 핵심 대상·개념(성분명, 제품 유형, 제도 용어).
   - 같은 말의 반복 변형(예: "NMN"과 "NMN 효과"처럼 한쪽이 다른 쪽에 통째로
     들어가는 것)은 하나만 남기고, "건강", "정보", "추천" 같은 너무 넓은 단어,
     본문에서 다루지 않은 내용, 글의 입장과 모순되는 용어는 넣지 마.
   (예: 유산균 보장균수, 유산균 균주명, 유산균 고르는 법, 프로바이오틱스 표시기준)"""

    return create_text(
        client,
        model="claude-sonnet-5-5",
        max_tokens=16000,  # 생각(thinking)에 쓰는 토큰까지 포함한 한도 — 본문은 이 중 일부만 씀
        system=STYLE_GUIDE,
        messages=[{"role": "user", "content": prompt}]
    )


def revise_draft(draft, issues, key_points, sources=None, personal_take="",
                 author_note="", platform="네이버 블로그", target_keyword="", style_sample=None):
    """점검에서 지적된 부분을 반영해 초안을 다듬는다 (초안 → 점검 → 수정본).

    draft: 현재 초안 전체 (태그 포함)
    issues: 고쳐야 할 지적 리스트 (collect_issues 결과)
    key_points/sources/personal_take: 처음 입력한 원재료 — 새 사실의 유일한 출처
    author_note: 이번에 추가로 알려주는 사실/의견 (선택) — 이것도 사실로 써도 됨
    """
    points_text = "\n".join(f"- {p}" for p in key_points)
    sources_text = "\n".join(f"- {s}" for s in (sources or [])) or "(없음)"
    issues_text = "\n".join(f"- {i}" for i in issues) or "(자동 점검 지적 없음 — 아래 저자 메모만 반영)"
    style_hint = PLATFORM_STYLE_HINTS.get(platform, PLATFORM_STYLE_HINTS["네이버 블로그"])

    if style_sample is None:
        style_sample = load_style_sample()

    prompt = f"""아래 블로그 초안을 점검 결과에 맞춰 다듬어줘.
{_style_block(style_sample)}
플랫폼: {style_hint}
타깃 키워드: {target_keyword or "(지정 안 함)"}

[현재 초안]
{draft}

[점검에서 지적된 부분]
{issues_text}

[저자가 이번에 추가로 알려준 내용]
{author_note or "(없음)"}

[처음에 제공된 사실/경험 — 새 내용을 쓸 때 쓸 수 있는 유일한 재료]
{points_text}

[제공된 참고 자료/출처]
{sources_text}

[저자의 의견/입장]
{personal_take or "(별도 입력 없음)"}

다듬기 규칙:
- 지적된 부분만 고치고, 문제 없는 부분의 좋은 문장·구조·내용은 그대로 둬.
  처음부터 새로 쓰지 마.
- 새 내용(사실, 숫자, 사례, 출처)은 위 "저자가 추가로 알려준 내용",
  "처음에 제공된 사실/경험", "제공된 참고 자료/출처"에 있는 것만 써.
  재료가 없어서 못 고치는 지적(예: 구체성 부족인데 쓸 사례가 없음)은
  지어내지 말고 그대로 두거나, 그 자리에 [추가 필요: 어떤 정보가 있으면
  좋은지]라고 표시해.
- 재료가 없어도 고칠 수 있는 지적은 반드시 고쳐: 근거가 제시되지 않은 일반론·
  단정 문장("~라는 말이 나온다", 교과서적 설명 등)은 삭제하거나 근거 있는 범위로
  좁혀 쓰고, 범위만 제시돼 모호한 수치는 "최대 ~"처럼 확인된 범위까지만 말하도록
  바꾸고, 뻔한 설명은 줄여서 저자의 판단과 구체 사례가 더 돋보이게 해.
  (새 사실을 더하는 게 아니라 빼거나 좁히는 방향이야.)
- [출처 필요]는 제공된 출처로 채울 수 있을 때만 채우고, 아니면 그대로 둬.
- [근거 없는 숫자] 지적은 재료에 있는 정확한 숫자로 바로잡고, 재료에서 확인할 수
  없으면 그 숫자를 빼고 문장을 고쳐 (짐작으로 다른 숫자를 넣지 마).
- [AI 말투] 지적은 같은 뜻을 다른 표현으로 바꿔서 반복을 없애고, 같은 어미가
  이어지면 어미를 바꿔 리듬을 줘.
{AI_HABITS_RULE}
- 표시광고 표현 지적은 "이런 표현은 쓰면 안 된다"는 설명 문맥이면 그대로 두고,
  글쓴이가 직접 그런 효능을 주장하는 문장이면 사실 전달 표현으로 바꿔.
- 처음 두 문장에 "요즘/최근"을 쓰거나 "~하세요/확인하세요" 식 뻔한 조언체로
  채우는 등 이미 금지된 패턴이 새로 생기지 않게 해.
- 형식은 현재 초안과 똑같이 유지해: [제목], [카테고리], [메타설명], [주소],
  본문 안의 [소제목]/[사진 제안]/[그래프 제안]/[지도 제안]/[내부링크 제안],
  마지막 [태그]. 마크다운 기호(#, * 등)는 쓰지 마. 분량도 비슷하게.
- 수정본 전체만 출력해. 설명이나 변경 내역은 붙이지 마."""

    return create_text(
        client,
        model="claude-sonnet-5-5",
        max_tokens=16000,  # 생각(thinking)에 쓰는 토큰까지 포함한 한도 — 본문은 이 중 일부만 씀
        system=STYLE_GUIDE,
        messages=[{"role": "user", "content": prompt}]
    )


def suggest_questions(topic):
    """주제에 맞는 브레인스토밍 질문을 만들어준다 (Haiku, 저비용)."""
    prompt = f"""블로그 주제: {topic}

이 주제로 글을 쓰려는 사람이 자기가 이미 알고 있는 실제 경험/숫자/사례를
떠올릴 수 있도록 돕는 질문을 4~5개 만들어줘. 일반론을 묻지 말고,
그 사람의 구체적인 기억이나 의견을 끄집어내는 질문이어야 해.
그중 최소 1개는 "이 주제에 대해 사람들이 흔히 하는 뻔한 얘기랑, 본인만
다르게 보거나 남들은 잘 모르는 지점이 뭔지" 를 묻는 질문으로 넣어줘 —
이미 다른 글에도 똑같이 나오는 뻔한 내용이 되지 않게 하려는 거야.

한 줄에 질문 하나씩, 번호나 설명 없이 질문 문장만 출력해."""

    try:
        message = client.messages.create(
            model="claude-haiku-5-5",
            max_tokens=1500,
            extra_body={"output_config": {"effort": "low"}},
            messages=[{"role": "user", "content": prompt}]
        )
        lines = extract_text(message).strip().split("\n")
        return [line.strip("-• ").strip() for line in lines if line.strip()]
    except Exception as e:
        print(f"⚠️ 질문 생성 실패 (건너뜀): {e}")
        return []
