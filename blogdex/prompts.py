def _place_block(place: dict | None) -> str:
    if not place or not place.get("name"):
        return ""
    lines = ["[업체 정보 - 지도 검색 결과이므로 사실로 사용 가능]"]
    for label, key in (("상호", "name"), ("업종", "category"), ("주소", "address"), ("전화", "phone")):
        if place.get(key):
            lines.append(f"- {label}: {place[key]}")
    return "\n".join(lines)


