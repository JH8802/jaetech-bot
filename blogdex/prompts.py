def format_place(place: dict) -> str:
    """지도 검색으로 확인한 매장 정보를 프롬프트용 문장으로 바꿉니다."""
    lines = ["[확인된 매장 정보 - 지도 검색 결과이므로 사실로 사용 가능]"]
    for label, key in (("상호", "name"), ("업종", "category"), ("주소", "address"), ("전화", "phone")):
        if place.get(key):
            lines.append(f"- {label}: {place[key]}")
    return "\n".join(lines)


def build_title_prompt(kind: str, keyword: str, extra: str, exclude: list[str]) -> str:
    t = POST_TYPES[kind]
    parts = [
        f"글 종류: {t['label']}",
        f"주제/키워드: {keyword}",
    ]
    if extra:
        parts.append(f"추가 정보: {extra}")
    if exclude:
        parts.append("아래 제목들과 겹치지 않는 새로운 방향으로 써주세요:\n" + "\n".join(f"- {x}" for x in exclude))
    parts.append(
        "\n네이버 블로그 검색 노출에 유리한 제목 5개를 제안하세요.\n"
        "- 핵심 키워드를 제목 앞쪽에 배치\n"
        "- 공백 포함 25~35자\n"
        "- 허위·과장·낚시성 표현 금지\n"
        "- 5개는 서로 다른 각도(질문형, 숫자형, 후기형, 방법형 등)로 작성\n"
        "- 한 줄에 제목 하나만, 번호·따옴표·부연 설명 없이 출력"
    )
    return "\n".join(parts)


def build_article_prompt(kind: str, title: str, extra: str, n_photos: int = 0) -> str:
    t = POST_TYPES[kind]
    parts = [
        f"글 종류: {t['label']}",
        f"[이 종류의 작성 지침]\n{t['guide']}",
        f"글 제목: {title}",
    ]
    if extra:
        label = "커스텀 지침" if kind == "custom" else "추가 정보"
        parts.append(f"{label}:\n{extra}")
    if n_photos:
        parts.append(
            f"[첨부 사진 지침]\n"
            f"사진 {n_photos}장이 위에 '사진 1' ~ '사진 {n_photos}' 순서로 첨부되어 있습니다.\n"
            "- 사진 내용을 보고, 글 흐름에 어울리는 위치에 [사진 N] 을 한 줄로 단독으로 넣으세요. "
            "모든 사진을 한 번씩만 쓰고, 사진 바로 앞뒤 문단은 그 사진 내용과 맞게 쓰세요.\n"
            "- 사진에서 실제로 보이는 음식·분위기·구도만 묘사하세요. "
            "메뉴명·가격·원산지가 사진(메뉴판 등)에서 읽히지 않거나 다른 정보에 없으면 지어내지 마세요.\n"
            "- 이 경우 [이미지: ...] 표기는 쓰지 마세요."
        )
    parts.append("\n위 제목으로 블로그 원고를 작성하세요. 첫 줄은 제목 그대로 쓰고, 한 줄 띄운 뒤 본문을 시작하세요.")
    return "\n\n".join(parts)
