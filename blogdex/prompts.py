def build_system(kind: str, guardrail: bool, evidence_mode: str, photo_count: int = 0, style_sample: str = "",
                 has_news: bool = False, register: str = "") -> str:
    if kind == "invest":
        return _build_invest_system(style_sample, has_news, photo_count, register)
    parts = [BASE_ROLE, PERSONA]
    if style_sample and style_sample.strip():
        parts.append(STYLE_SAMPLE_HEAD + style_sample.strip()[:MAX_STYLE_SAMPLE] + STYLE_SAMPLE_TAIL)
    parts += [KIND_SPECS[kind], TAG_RULES, WRITING_RULES, SEO_RULES]
    if kind in PLACE_KINDS:
        parts.append(RATING_RULES)
    parts.append(EVIDENCE_STRICT if evidence_mode == "strict" else EVIDENCE_TEMPLATE)
    parts.append(NO_META)
    parts.append(PHOTO_RULES if photo_count else NO_PHOTO)
    parts.append(INFO_LAYOUT_RULES)
    if has_news:
        parts.append(NEWS_RULES)
    if guardrail:
        parts.append(GUARDRAIL)
    return "\n\n".join(parts)


def derive_keywords(kind: str, title: str, place: dict | None) -> list[str]:
    """제목과 업체 정보에서 핵심 키워드 후보를 뽑습니다. (화면에서 사용자가 수정 가능)"""
    kws: list[str] = []
    place = place or {}
    if kind in PLACE_KINDS and place.get("name"):
        name = place["name"].strip()
        kws.append(name)
        first = name.split()[0]
        if first != name:
            kws.append(first)
        m = re.search(r"([가-힣]{2,})구", place.get("address", ""))
        if m:
            kws.append(m.group(1))
    head = re.split(r"[,，]", title or "")[0].split()
    if kind == "info" and head:
        kws.append(" ".join(head[:2]))
    if kind == "food":
        kws += re.findall(r"[가-힣]{2,}역", title or "")
    seen, out = set(), []
    for k in kws:
        if k and k not in seen:
            seen.add(k)
            out.append(k)
    return out[:6]


def _place_block(place: dict | None) -> str:
    if not place or not place.get("name"):
        return ""
    lines = ["[업체 정보 - 지도 검색 결과이므로 사실로 사용 가능]"]
    for label, key in (("상호", "name"), ("업종", "category"), ("주소", "address"), ("전화", "phone")):
        if place.get(key):
            lines.append(f"- {label}: {place[key]}")
    return "\n".join(lines)


